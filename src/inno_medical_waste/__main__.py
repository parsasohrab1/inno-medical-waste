"""Command line: generate synthetic data, validate (TRL 4 criteria), run a demo."""
import argparse, csv, json, os, sys
from . import core


def write_tables(tables, out):
    os.makedirs(out, exist_ok=True)
    for name, rows in tables.items():
        if not rows:
            continue
        with open(os.path.join(out, name + ".csv"), "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)


OPS = {">=": lambda a, b: a >= b, "<=": lambda a, b: a <= b}


def check(metrics):
    res = []
    for key, op, thr, desc in core.CRITERIA:
        v = metrics[key]
        res.append({"metric": key, "op": op, "threshold": thr, "value": round(float(v), 4),
                    "pass": bool(OPS[op](v, thr)), "description": desc})
    return res


def validate(seed=0, seeds=3):
    runs = []
    for s in range(seed, seed + seeds):
        m = core.evaluate(s)
        runs.append({"seed": s, "metrics": {k: (round(v, 4) if isinstance(v, float) else v) for k, v in m.items()}, "criteria": check(m)})
    ok = all(c["pass"] for r in runs for c in r["criteria"])
    return {"package": "inno_medical_waste", "trl_claim": 4, "data": "synthetic only", "all_pass": ok, "runs": runs}


def to_markdown(rep):
    lines = ["# Validation report (synthetic data, lab)", "", "Generated by `python -m inno_medical_waste validate`. Overall: **%s**" % ("PASS" if rep["all_pass"] else "FAIL"), ""]
    first = rep["runs"][0]["criteria"]
    seeds = [str(r["seed"]) for r in rep["runs"]]
    lines.append("| Criterion | Requirement | " + " | ".join("seed " + s for s in seeds) + " |")
    lines.append("|---|---|" + "---|" * len(seeds))
    for i, c in enumerate(first):
        vals = " | ".join(("%s %s" % (r["criteria"][i]["value"], "✔" if r["criteria"][i]["pass"] else "✘")) for r in rep["runs"])
        lines.append("| %s | %s %s | %s |" % (c["description"], c["op"], c["threshold"], vals))
    lines += ["", "Raw metrics per seed are in `docs/validation_report.json`.", ""]
    return "\n".join(lines)


def main(argv=None):
    p = argparse.ArgumentParser(prog="inno_medical_waste", description=__doc__)
    sub = p.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate"); g.add_argument("--out", default="data/sample"); g.add_argument("--seed", type=int, default=0)
    v = sub.add_parser("validate"); v.add_argument("--seed", type=int, default=0); v.add_argument("--no-write", action="store_true")
    d = sub.add_parser("demo"); d.add_argument("--seed", type=int, default=0)
    a = p.parse_args(argv)
    if a.cmd == "generate":
        write_tables(core.generate(a.seed), a.out); print("wrote", a.out)
    elif a.cmd == "validate":
        rep = validate(a.seed)
        if not a.no_write:
            os.makedirs("docs", exist_ok=True)
            json.dump(rep, open("docs/validation_report.json", "w", encoding="utf-8"), indent=2, ensure_ascii=False)
            open("docs/VALIDATION.md", "w", encoding="utf-8").write(to_markdown(rep))
        print(to_markdown(rep)); return 0 if rep["all_pass"] else 1
    else:
        print(core.demo(a.seed))
    return 0


if __name__ == "__main__":
    sys.exit(main())
